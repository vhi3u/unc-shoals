function dshoal_selftest(verbose)
% DSHOAL_SELFTEST  Check dshoal_bottom.m against the Julia it mirrors.
%
%   dshoal_selftest()        % errors on drift, prints one line on success
%   dshoal_selftest(false)   % silent on success
%
% A second copy of a function the model actually runs is how
% MATLAB/shoal_stuff/plot_shoals.m came to draw a 100x300 km domain with the
% retired Hs/shelf_length parameterization long after the model had moved to
% Zs/Zsh on 150x200 km. The figure and the simulation diverged and nothing
% complained. The copy is unavoidable -- this runs on a laptop with no Julia
% -- so instead it is made detectable.
%
% Regenerate REF after an INTENDED change to the Julia:
%
%   julia --project=. tools/plot_bathy_compare.jl --emit-ref
%
% and paste the output over reference_table() below. That script calls the
% Julia function directly, so it is the authority if the two disagree.

if nargin < 1, verbose = true; end
REF = reference_table();
worst = 0; wrow = [];
for i = 1:size(REF, 1)
    got = dshoal_bottom(REF(i,1)*1e3, REF(i,2)*1e3, 'Ly', 200e3, ...
                        'Zs', REF(i,3), 'Zc', REF(i,4), 'Ls', 40e3, ...
                        'sigma', 8e3, 'Zsh', -25.0, 'shelf_break_end', 12.0e3);
    d = abs(got - REF(i,5));
    if d > worst, worst = d; wrow = [REF(i,:) got]; end
end
if worst > 1e-9
    error('dshoal_selftest:drift', ...
        ['Bathymetry does not match the Julia source (max error %.3g m).\n' ...
         '  worst: x = %g km, y = %g km, Zs = %g, Zc = %g\n' ...
         '         julia = %.10f    matlab = %.10f\n' ...
         'tools/dshoal_bottom.m and src/dshoal_vn_param.jl have diverged.\n' ...
         'Fix the translation, or regenerate REF if the Julia change was intended.'], ...
        worst, wrow(1), wrow(2), wrow(3), wrow(4), wrow(5), wrow(6));
end
if verbose
    fprintf('selftest: %d reference points match the Julia source (max err %.2g m)\n', ...
            size(REF,1), worst);
end
end

